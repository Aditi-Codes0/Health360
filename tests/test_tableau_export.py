"""
Health 360: Unit Tests for Tableau Export Pipeline & Manifest
"""

import pytest
import pandas as pd
from pathlib import Path
from src.tableau_export import TableauExporter


@pytest.fixture
def exporter(tmp_path):
    return TableauExporter(export_dir=tmp_path)


def test_export_dataset_and_manifest(exporter, tmp_path):
    """Verify CSV export and manifest metadata compilation."""
    sample_df = pd.DataFrame({
        "Disease": ["Heart Disease", "Diabetes"],
        "Cases": [100, 200]
    })
    out_file = exporter.export_dataset(
        sample_df,
        filename="test_export.csv",
        description="Test export file",
        grain="Disease Grain",
        target_dashboard="Test Dashboard"
    )
    assert out_file.exists()
    loaded = pd.read_csv(out_file)
    assert len(loaded) == 2
    assert len(exporter.manifest_entries) == 1
    assert exporter.manifest_entries[0]["file_name"] == "test_export.csv"


def test_exported_tableau_files_exist():
    """Verify that all production Tableau files generated by pipeline exist and are non-empty."""
    from config import settings
    expected_files = [
        "clean_patient_data.csv",
        "disease_prevalence.csv",
        "age_group_analysis.csv",
        "bmi_category_analysis.csv",
        "clinical_indicator_summary.csv",
        "lifestyle_analysis.csv",
        "symptom_analysis.csv",
        "correlation_matrix.csv",
        "risk_factor_associations.csv",
        "population_segments.csv",
        "model_metrics.csv",
        "feature_importance.csv",
        "data_quality_report.csv",
        "tableau_export_manifest.json"
    ]
    for fname in expected_files:
        fpath = settings.TABLEAU_DIR / fname
        assert fpath.exists(), f"Missing expected Tableau export file: {fname}"
        assert fpath.stat().st_size > 0, f"Tableau export file is empty: {fname}"
